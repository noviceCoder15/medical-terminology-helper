def cmd_fetch(args) -> int:
    url = args.url or storage.DEFAULT_SOURCE_URL
    if args.name:
        name = args.name
    elif args.url:
        name = re.sub(r"[^a-z0-9]+", "-", url.lower()).strip("-")[-40:]
    else:
        name = storage.DEFAULT_SOURCE_NAME
    try:
        path, n_chars = storage.fetch_corpus(url, name, args.data)
    except (urllib.error.URLError, TimeoutError, ConnectionError) as exc:
        raise RuntimeError(f"could not download {url}: {exc}") from exc
    print(f"saved {n_chars:,} characters to {path}")
    print("Project Gutenberg lists its texts as public domain in the USA - "
          "check the terms for your own country before sharing them.")
    return 0


def cmd_tokens(args) -> int:
    tokenizer = storage.load_tokenizer(args.tokenizer)
    text = " ".join(args.text)
    ids = tokenizer.encode(text)
    shown = [tokenizer.token_text(i).replace(" ", "\u00b7").replace("\n", "\\n") for i in ids]
    print("|".join(shown))
    print(f"{len(text)} characters -> {len(ids)} tokens   (\u00b7 marks a space)")
    print("ids:", ids)
    return 0


def cmd_train(args) -> int:
    import torch

    from . import llm

    seed = args.seed if args.seed is not None else 1337
    text, files = storage.load_corpus(args.data, args.max_chars)
    train_text, val_text = core.split_paragraphs(text, args.val_fraction, seed)
    print(f"corpus   : {len(text):,} characters from {', '.join(files)}")

    tokenizer = core.BPETokenizer().train(train_text, args.vocab_size)
    train_ids = tokenizer.encode(train_text)
    val_ids = tokenizer.encode(val_text)
    print(f"tokenizer: {tokenizer.vocab_size} tokens "
          f"({len(tokenizer.merges)} merges), {len(train_text) / len(train_ids):.2f} characters per token")
    needed = args.block_size + 2
    if len(train_ids) < needed or len(val_ids) < needed:
        raise ValueError(
            f"the corpus is too small for a block size of {args.block_size} "
            f"({len(train_ids)} training and {len(val_ids)} validation tokens) - "
            "add more text, or lower --block-size"
        )

    torch.manual_seed(seed)
    model = llm.GPT(llm.GPTConfig(
        vocab_size=tokenizer.vocab_size, block_size=args.block_size, n_layer=args.n_layer,
        n_head=args.n_head, n_embd=args.n_embd, dropout=args.dropout,
    ))
    print(f"model    : {llm.count_parameters(model):,} parameters, "
          f"{len(train_ids):,} training tokens, {len(val_ids):,} validation tokens\n")

    result = llm.train(
        model,
        torch.tensor(train_ids, dtype=torch.long),
        torch.tensor(val_ids, dtype=torch.long),
        args.steps, args.batch_size, args.lr, args.eval_every, seed,
    )
    storage.save_checkpoint(args.model, model, tokenizer, {
        "best_val_loss": result["best_val_loss"], "steps": args.steps, "files": files,
    })
    storage.save_tokenizer(args.tokenizer, tokenizer)
    print(f"\nbest validation loss {result['best_val_loss']:.3f}; saved {args.model}")

    sample = llm.complete(model, tokenizer, "The", 30, seed=seed)
    print(f"\nsample: {sample.prompt}{sample.text}")
    print(f"\n{DISCLAIMER}")
    return 0


def cmd_complete(args) -> int:
    phrase = " ".join(args.phrase)
    model, tokenizer = storage.load_checkpoint(args.model)
    from . import llm

    result = llm.complete(model, tokenizer, phrase, args.length, args.temperature, args.top_k, args.seed)
    print(result.prompt + result.text)
    if args.show_probs:
        print()
        print(probability_table(result))
    print(f"\n{DISCLAIMER}")
    return 0


def run_chat(model, tokenizer, args, input_fn=input, out=print) -> int:
    """Interactive loop: enter a partial phrase, get a completion. /quit to leave."""
    from . import llm

    out("Medical Terminology Helper - enter a partial phrase or definition, or /quit")
    out(DISCLAIMER)
    while True:
        try:
            raw = input_fn("phrase> ").strip()
        except (EOFError, KeyboardInterrupt):
            out("")
            break
        if not raw:
            continue
        if raw in ("/quit", "/exit", "/q"):
            break
        result = llm.complete(model, tokenizer, raw, args.length, args.temperature, args.top_k, args.seed)
        out(result.prompt + result.text)
        if args.show_probs:
            out(probability_table(result))
    return 0


def cmd_chat(args) -> int:
    model, tokenizer = storage.load_checkpoint(args.model)
    return run_chat(model, tokenizer, args)


# --------------------------------------------------------------------------
# argument parsing
# --------------------------------------------------------------------------

def build_parser() -> argparse.ArgumentParser:
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--data", default=_env("MED_DATA", "data"),
                        help="a .txt file, or a folder of .txt files (default: data)")
    common.add_argument("--model", default=_env("MED_MODEL_PATH", "models/medical_gpt.pt"))
    common.add_argument("--tokenizer", default=_env("MED_TOKENIZER_PATH", "models/tokenizer.json"))
    common.add_argument("--seed", type=int, default=_env_int("MED_SEED"),
                        help="fix the random seed for repeatable results")

    sampling = argparse.ArgumentParser(add_help=False)
    sampling.add_argument("--length", type=int, default=40, help="how many tokens to generate (default 40)")
    sampling.add_argument("--temperature", type=float, default=0.8,
                          help="0 = most likely word every time, higher = more varied (default 0.8)")
    sampling.add_argument("--top-k", type=int, default=40, help="only sample from the k most likely tokens")
    sampling.add_argument("--show-probs", action="store_true",
                          help="show the probability the model gave each generated token")

    parser = argparse.ArgumentParser(
        prog="python -m app.cli",
        description="Complete medical phrases and definitions with a GPT trained from scratch "
                    "on public domain medical texts.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    fetch = sub.add_parser("fetch", parents=[common], help="download a public domain text into the data folder")
    fetch.add_argument("--url", help="plain-text URL (default: a Project Gutenberg anatomy and physiology book)")
    fetch.add_argument("--name", help="file name to save it under (without .txt)")
    fetch.set_defaults(func=cmd_fetch)

    tok = sub.add_parser("tokens", parents=[common], help="show how the trained BPE tokenizer splits text")
    tok.add_argument("text", nargs="+")
    tok.set_defaults(func=cmd_tokens)

    train = sub.add_parser("train", parents=[common], help="train the BPE tokenizer and the GPT")
    train.add_argument("--max-chars", type=int, default=400_000, help="use at most this much text (default 400000)")
    train.add_argument("--val-fraction", type=float, default=0.1)
    train.add_argument("--vocab-size", type=int, default=512, help="BPE vocabulary size (default 512)")
    train.add_argument("--block-size", type=int, default=64, help="context length in tokens (default 64)")
    train.add_argument("--n-layer", type=int, default=4)
    train.add_argument("--n-head", type=int, default=4)
    train.add_argument("--n-embd", type=int, default=128)
    train.add_argument("--dropout", type=float, default=0.1)
    train.add_argument("--batch-size", type=int, default=32)
    train.add_argument("--steps", type=int, default=1500)
    train.add_argument("--lr", type=float, default=1e-3)
    train.add_argument("--eval-every", type=int, default=100)
    train.set_defaults(func=cmd_train)

    comp = sub.add_parser("complete", parents=[common, sampling], help="complete a partial phrase or definition")
    comp.add_argument("phrase", nargs="+", help='for example: The femur is')
    comp.set_defaults(func=cmd_complete)

    chat = sub.add_parser("chat", parents=[common, sampling], help="enter phrases one after another")
    chat.set_defaults(func=cmd_chat)

    return parser


def main(argv=None) -> int:
    storage.load_env()
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except ModuleNotFoundError as exc:
        if exc.name != "torch":
            raise
        print("error: PyTorch is needed for this command - install it with: pip install torch",
              file=sys.stderr)
        return 1
    except (OSError, ValueError, RuntimeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
