"""Command line interface for the Medical Terminology Helper.

    python -m app.cli fetch                     # download a public domain text
    python -m app.cli train                     # train the tokenizer and the GPT
    python -m app.cli complete "The femur is"   # complete a partial phrase
    python -m app.cli chat                      # keep entering phrases
    python -m app.cli tokens "tachycardia"      # see how the BPE tokenizer splits text
"""
from __future__ import annotations

import argparse
import os
import re
import sys
import urllib.error

from . import core, storage

DISCLAIMER = (
    "Generated by a small model for vocabulary practice. It can sound right and be wrong - "
    "check anything that matters in a textbook, and never use it for medical decisions."
)


def _env(name: str, default: str) -> str:
    return os.environ.get(name, default)


def _env_int(name: str):
    value = os.environ.get(name, "")
    return int(value) if value else None


def format_table(headers, rows) -> str:
    widths = [
        max([len(str(h))] + [len(str(row[i])) for row in rows])
        for i, h in enumerate(headers)
    ]
    line = "  ".join(str(h).ljust(w) for h, w in zip(headers, widths))
    rule = "  ".join("-" * w for w in widths)
    body = ["  ".join(str(c).ljust(w) for c, w in zip(row, widths)) for row in rows]
    return "\n".join([line, rule] + body)


def probability_table(completion) -> str:
    """Each generated token and the probability the model gave it."""
    rows = [[repr(piece), f"{p:.3f}"] for piece, p in completion.tokens]
    average = sum(p for _, p in completion.tokens) / max(1, len(completion.tokens))
    return format_table(["token", "probability"], rows) + f"\naverage probability: {average:.3f}"


